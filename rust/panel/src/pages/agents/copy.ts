export type AgentCopyKey = keyof typeof tr;
export type AgentCopy = ((key: AgentCopyKey, vars?: Record<string, string | number>) => string) & { language: string; isTurkish: boolean };

export function useAgentCopy(): AgentCopy {
  const { i18n } = useTranslation();
  const language = i18n.resolvedLanguage ?? i18n.language;
  const isTurkish = language.startsWith('tr');
  const table = isTurkish ? tr : en;
  const copy = ((key: AgentCopyKey, vars: Record<string, string | number> = {}) =>
    table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))) as AgentCopy;
  copy.language = language;
  copy.isTurkish = isTurkish;
  return copy;
}

/** Both tables, for the parity test. */
