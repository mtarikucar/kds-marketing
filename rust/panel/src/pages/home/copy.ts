/** The actions each table words, for the test that holds them to the server's names. */
export const actionCodes = { tr: Object.keys(actionsTr), en: Object.keys(actionsEn) };

export type HomeCopyKey = keyof typeof tr;
export type HomeCopy = ((key: HomeCopyKey, vars?: Record<string, string | number>) => string) & {
  action: (code: string, payload?: unknown) => string | null;
  isTurkish: boolean;
};

export function useHomeCopy(): HomeCopy {
  const { i18n } = useTranslation();
  const isTurkish = (i18n.resolvedLanguage ?? i18n.language).startsWith('tr');
  const table = isTurkish ? tr : en;
  const actions = isTurkish ? actionsTr : actionsEn;
  const copy = ((key: HomeCopyKey, vars: Record<string, string | number> = {}) =>
    table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))) as HomeCopy;
  copy.action = (code, payload) => {
    const state = payload !== null && typeof payload === 'object' ? (payload as { state?: unknown }).state : null;
    return (typeof state === 'string' ? actions[`${code}:${state}`] : undefined) ?? actions[code] ?? null;
  };
  copy.isTurkish = isTurkish;
  return copy;
}
