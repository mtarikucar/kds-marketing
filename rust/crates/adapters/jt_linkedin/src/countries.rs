/// LinkedIn's name of the country `code` (two uppercase letters), when its table has one.
pub(crate) fn name_of(code: &str) -> Option<&'static str> {
    COUNTRIES
        .iter()
        .find(|(listed, _)| *listed == code)
        .map(|(_, name)| *name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_code_is_listed_once_and_named() {
        assert_eq!(COUNTRIES.len(), 242);
        for (n, (code, name)) in COUNTRIES.iter().enumerate() {
            assert!(
                code.len() == 2 && code.bytes().all(|b| b.is_ascii_uppercase()),
                "{code}"
            );
            assert!(!name.trim().is_empty(), "{code}");
            assert!(
                COUNTRIES[..n].iter().all(|(other, _)| other != code),
                "{code} twice"
            );
        }
        assert_eq!(name_of("TR"), Some("Türkiye"));
        assert_eq!(name_of("DE"), Some("Germany"));
        assert_eq!(name_of("XX"), None);
        assert_eq!(name_of("tr"), None);
    }
}
